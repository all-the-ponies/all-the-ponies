// Test/demo infrastructure only: production still uses ATP's asset resolver.
import http from 'node:http'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import { createServer } from 'vite'
import vue from '@vitejs/plugin-vue'

const root = fileURLToPath(new URL('../../', import.meta.url))
const digest = bytes => createHash('sha256').update(bytes).digest('hex')

export async function startDemo(port = 5195) {
    if (!process.env.MODEL_VIEWER_ASSETS) {
        throw new Error('Set MODEL_VIEWER_ASSETS to the game-data dist directory containing models_3d.json and models/3d/.')
    }
    const generated = path.resolve(process.env.MODEL_VIEWER_ASSETS)
    let document
    try {
        document = JSON.parse(await fs.readFile(path.join(generated, 'models_3d.json'), 'utf8'))
    } catch (cause) {
        throw new Error(`Cannot read ${path.join(generated, 'models_3d.json')}. Set MODEL_VIEWER_ASSETS to a completed game-data output directory.`, { cause })
    }
    if (!document?.models || typeof document.models !== 'object' || Array.isArray(document.models)) {
        throw new Error('models_3d.json must contain a models object. Use the catalogue generated by game-data.')
    }
    // The picker only needs IDs. The production resolver validates each selected
    // resource, its catalogue schema, rig and path before the viewer loads it.
    const identities = Buffer.from(JSON.stringify(Object.keys(document.models).sort()))
    // As with ATP's uploader, JSON may be serialized again. Catalogue identity
    // comes from the final manifest; binary resources retain their own SHA.
    const catalogue = Buffer.from(JSON.stringify(document))
    const manifest = Buffer.from(JSON.stringify({ 'models_3d.json': digest(catalogue) }))
    const requests = []
    const assets = http.createServer(async (request, response) => {
        const key = new URL(request.url, 'http://localhost').pathname.slice(1)
        requests.push(key)
        response.setHeader('Access-Control-Allow-Origin', '*')
        response.setHeader('Cache-Control', 'no-cache')
        try {
            if (key === 'manifest.json' || key === 'models_3d.json') {
                response.setHeader('Content-Type', 'application/json')
                response.end(key === 'manifest.json' ? manifest : catalogue)
            } else if (/^models\/3d\/(?:[A-Za-z0-9_-]+|[a-f0-9]{64}\/[A-Za-z0-9_-]+)\.glb$/.test(key)) {
                response.setHeader('Content-Type', 'model/gltf-binary')
                response.end(await fs.readFile(path.join(generated, key)))
            } else {
                response.writeHead(404).end()
            }
        } catch {
            response.writeHead(404).end()
        }
    })
    await new Promise((resolve, reject) => {
        assets.once('error', reject)
        assets.listen(0, '127.0.0.1', resolve)
    })
    const assetOrigin = `http://127.0.0.1:${assets.address().port}`
    let vite
    try {
        vite = await createServer({
            root, configFile: false, publicDir: path.join(root, 'public'),
            resolve: { alias: { '@': path.join(root, 'src') } },
            optimizeDeps: { include: ['vue', 'vue-i18n', 'vike-vue/usePageContext', 'vike-vue/ClientOnly', 'three', 'three/addons/loaders/GLTFLoader.js', 'three/addons/controls/OrbitControls.js'] },
            plugins: [vue(), {
                name: 'model-viewer-test-cdn',
                enforce: 'pre',
                configureServer(server) {
                    server.middlewares.use(async (request, response, next) => {
                        const pathname = new URL(request.url, 'http://localhost').pathname
                        if (pathname === '/__model-viewer-identities.json') {
                            response.setHeader('Content-Type', 'application/json')
                            response.setHeader('Cache-Control', 'no-cache')
                            return response.end(identities)
                        }
                        if (pathname !== '/') return next()
                        const source = '<!doctype html><html lang="en"><head><meta name="viewport" content="width=device-width, initial-scale=1"><title>ATP 3D model viewer</title></head><body><div id="app"></div><script type="module" src="/tests/model-viewer/demo.ts"></script></body></html>'
                        response.setHeader('Content-Type', 'text/html')
                        response.end(await server.transformIndexHtml(request.url, source))
                    })
                },
                resolveId(source, importer) {
                    if (source === '../../scripts/assets' && importer?.split('?')[0].endsWith('/model-viewer/assets.ts')) {
                        return '\0model-viewer-test-assets'
                    }
                },
                load(id) {
                    if (id === '\0model-viewer-test-assets') {
                        return `export const createAssetUrl = key => new URL(key, ${JSON.stringify(assetOrigin + '/')}).href`
                    }
                },
            }],
            server: { host: '127.0.0.1', port, strictPort: true },
        })
        await vite.listen()
    } catch (error) {
        await vite?.close()
        await new Promise(resolve => assets.close(resolve))
        throw error
    }
    return {
        vite, assetOrigin, requests,
        url: `http://127.0.0.1:${port}`,
        async close() {
            await vite.close()
            await new Promise(resolve => assets.close(resolve))
        },
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const server = await startDemo(Number(process.env.MODEL_VIEWER_PORT || 5195))
    console.log(`ATP 3D model viewer: ${server.url}`)
    console.log(`Using game-data output: ${path.resolve(process.env.MODEL_VIEWER_ASSETS)}`)
    console.log('Model/animation assets are served by a separate local CORS-enabled origin.')
    for (const name of ['SIGINT', 'SIGTERM']) process.once(name, async () => { await server.close(); process.exit(0) })
}
