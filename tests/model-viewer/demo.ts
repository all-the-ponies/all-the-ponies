import { computed, createApp, h, ref } from 'vue'
import { createI18n } from 'vue-i18n'
import { setPageContext } from 'vike-vue/usePageContext'
import type { PageContext } from 'vike/types'
import messages from '../../src/locales/en.json'
import ModelViewerLauncher from '../../src/components/model-viewer/ModelViewerLauncher.vue'
import '../../src/assets/css/main.css'

const parameters = new URLSearchParams(location.search)
const response = await fetch('/__model-viewer-identities.json')
if (!response.ok) throw new Error('Cannot read the local model catalogue. Restart the demo with a completed game-data output directory.')
const identities: string[] = await response.json()
const identity = ref(parameters.has('identity')
    ? parameters.get('identity')!
    : identities.find(id => id.startsWith('Pony_')) ?? identities[0] ?? '')
const search = ref('')
const visibleIdentities = computed(() => identities.filter(id => id.toLowerCase().includes(search.value.toLowerCase())))
const available = computed(() => identities.includes(identity.value))
function selectIdentity(event: Event) {
    identity.value = (event.target as HTMLSelectElement).value
    const url = new URL(location.href)
    url.searchParams.set('identity', identity.value)
    history.replaceState(null, '', url)
}
const app = createApp({
    render: () => h('main', { style: 'max-width:52rem;margin:2rem auto;padding:1rem;overflow-wrap:anywhere' }, [
        h('h1', 'ATP 3D model viewer'),
        h('p', 'Browse the Pony, Pet and Costume models generated by game-data, using the same viewer as ATP object pages.'),
        h('div', { style: 'display:grid;gap:.5rem;max-width:100%;margin:1.5rem 0' }, [
            h('label', { for: 'model-search' }, 'Search Object IDs'),
            h('input', {
                id: 'model-search', type: 'search', value: search.value,
                style: 'min-width:0;width:100%;padding:.5rem',
                onInput: (event: Event) => { search.value = (event.target as HTMLInputElement).value },
            }),
            h('label', { for: 'model-identity' }, 'Model'),
            h('select', {
                id: 'model-identity', value: identity.value, size: 6,
                style: 'min-width:0;width:100%;padding:.5rem',
                onChange: selectIdentity,
            }, visibleIdentities.value.map(id => h('option', { value: id }, id))),
            h('p', `${visibleIdentities.value.length} of ${identities.length} catalogue identities shown`),
        ]),
        h('h2', identity.value || 'No models available'),
        !available.value ? h('p', { role: 'alert' }, identity.value
            ? `The requested identity “${identity.value}” is not in this catalogue. Select an available model above.`
            : 'This catalogue contains no models. Generate model resources with game-data, then restart this demo.') : null,
        // ObjectPage sets each right-buttons slot child to this size.
        available.value ? h(ModelViewerLauncher, { identity: identity.value, name: identity.value, style: 'width:3rem;height:3rem' }) : null,
        h('p', 'Open the 3D viewer to play an animation, switch between horizontal and free rotation, or reset the view. Pre-generated costumes, materials and supported additional objects load with the selected model.'),
        h('p', 'Only identities present in this local catalogue are listed. Excluded resources and unsupported game events are not added by this demo.'),
    ]),
})
app.use(createI18n({ legacy: false, locale: 'en', fallbackLocale: 'en', messages: { en: messages } }))
// Supply the client flags consumed by ATP's existing ClientOnly dialog. The
// production route obtains this context from Vike, not from this demo harness.
setPageContext(app, { isClientSide: true, isHydration: false, urlPathname: '/' } as PageContext)
app.mount('#app')

// A test-only entry for exercising the public runtime controller. The ordinary
// demo above uses exactly the production Vue components, without debug globals.
if (parameters.has('runtime')) {
    const { mountViewer } = await import('../../src/components/model-viewer/runtime')
    const { resolveModel } = await import('../../src/components/model-viewer/assets')
    const model = await resolveModel(identity.value, new AbortController().signal)
    if (!model) throw new Error(`No generated model exists for ${identity.value}`)
    const host = document.createElement('div')
    host.id = 'runtime-host'
    host.style.cssText = 'width:480px;height:480px;max-width:90vw;margin:1rem auto;background:#f0f4f8'
    document.body.append(host)
    const controller = mountViewer(host, model, () => {})
    Object.assign(window, { viewerTest: { controller, model, app } })
}
